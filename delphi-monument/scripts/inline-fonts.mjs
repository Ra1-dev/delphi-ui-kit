#!/usr/bin/env node
// Writes fonts.css with every woff2 inlined as a data URI, for pages where fonts cannot be fetched as files:
// a strict CSP (default-src 'self' without font files), a backend that serves a fixed list of files,
// desktop shells (pywebview, Electron, WebView2). Allow `font-src data:` in the CSP if it is set.
// Usage: node monument/scripts/inline-fonts.mjs [out.css] [fonts dir]
//   defaults: out = fonts-inline.css, fonts dir = the kit's fonts/ next to this script (or src/monument/fonts)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] ?? "fonts-inline.css";
const candidates = [process.argv[3], join(here, "..", "fonts"), "src/monument/fonts", "monument/fonts"].filter(Boolean);
const dir = candidates.map((d) => resolve(d)).find((d) => existsSync(join(d, "fonts.css")));
if (!dir) {
  console.error(`fonts.css not found in: ${candidates.join(", ")}. Pass the fonts folder as the second argument.`);
  process.exit(1);
}
const css = readFileSync(join(dir, "fonts.css"), "utf8").replace(/url\((?:'|")?\.\/([^)'"]+\.woff2)(?:'|")?\)/g, (_, file) => {
  const data = readFileSync(join(dir, file)).toString("base64");
  return `url(data:font/woff2;base64,${data})`;
});
writeFileSync(out, `/* Generated by monument/scripts/inline-fonts.mjs from the kit's fonts.css. Do not edit; regenerate. */\n${css}`);
console.log(`Wrote ${out} (${Math.round(Buffer.byteLength(css) / 1024)} KB).`);
